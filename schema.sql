-- ------------------------------------------------------------
-- Admin role helper
-- Uses SECURITY DEFINER so RLS can safely ask whether the caller
-- is an admin without exposing profile rows to anonymous users.
-- ------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

-- ------------------------------------------------------------
-- Condition helper for server-side response validation
-- ------------------------------------------------------------
create or replace function public.condition_matches_response(
  p_response jsonb,
  p_condition jsonb
)
returns boolean
language plpgsql
immutable
as $$
declare
  v_question_id text := p_condition->>'questionId';
  v_operator text := coalesce(p_condition->>'operator', 'eq');
  v_target text := coalesce(p_condition->>'value', '');
  v_value jsonb := p_response->v_question_id;
  v_text text := '';
begin
  if v_value is null or v_value = 'null'::jsonb then
    v_text := '';
  elsif jsonb_typeof(v_value) = 'array' then
    select coalesce(string_agg(value, '، '), '') into v_text
    from jsonb_array_elements_text(v_value);
  else
    v_text := coalesce(v_value #>> '{}', '');
  end if;

  case v_operator
    when 'empty' then return btrim(v_text) = '';
    when 'notempty' then return btrim(v_text) <> '';
    when 'contains' then return position(v_target in v_text) > 0;
    when 'starts' then return left(v_text, length(v_target)) = v_target;
    when 'ends' then return right(v_text, length(v_target)) = v_target;
    when 'neq' then return btrim(v_text) <> btrim(v_target);
    else return btrim(v_text) = btrim(v_target);
  end case;
end;
$$;

-- ------------------------------------------------------------
-- Question visibility helper
-- ------------------------------------------------------------
create or replace function public.question_is_visible(
  p_response jsonb,
  p_question jsonb
)
returns boolean
language plpgsql
immutable
as $$
declare
  v_conditions jsonb := coalesce(p_question->'conditions', '[]'::jsonb);
  v_mode text := coalesce(p_question->>'conditionMode', 'and');
  v_result boolean;
begin
  if jsonb_array_length(v_conditions) = 0 then
    return true;
  end if;

  if v_mode = 'or' then
    select exists (
      select 1
      from jsonb_array_elements(v_conditions) condition
      where public.condition_matches_response(p_response, condition)
    ) into v_result;
  else
    select not exists (
      select 1
      from jsonb_array_elements(v_conditions) condition
      where not public.condition_matches_response(p_response, condition)
    ) into v_result;
  end if;

  return coalesce(v_result, false);
end;
$$;

-- ------------------------------------------------------------
-- Validate and submit a public response.
-- This is SECURITY DEFINER and is the ONLY public write path.
-- ------------------------------------------------------------
create or replace function public.submit_public_response(
  p_form_id uuid,
  p_form_version_id uuid,
  p_response jsonb,
  p_device_name text default ''
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_version public.form_versions%rowtype;
  v_question jsonb;
  v_id text;
  v_value jsonb;
  v_text text;
  v_text_ascii text;
  v_validation jsonb;
  v_min numeric;
  v_max numeric;
  v_num numeric;
  v_options jsonb;
  v_schema jsonb;
  v_clean_response jsonb := '{}'::jsonb;
  v_response_id uuid;
begin
  if jsonb_typeof(p_response) <> 'object' then
    raise exception 'پاسخ باید یک شیء JSON باشد.' using errcode = '22023';
  end if;

  select * into v_version
  from public.form_versions
  where id = p_form_version_id
    and form_id = p_form_id
    and is_published = true;

  if not found then
    raise exception 'این نسخه فرم منتشرشده نیست یا وجود ندارد.' using errcode = '42501';
  end if;

  v_schema := v_version.questions;

  -- Reject unknown fields.
  if exists (
    select 1
    from jsonb_object_keys(p_response) key_name
    where not exists (
      select 1
      from jsonb_array_elements(v_schema) q
      where q->>'id' = key_name
    )
  ) then
    raise exception 'پاسخ شامل فیلد ناشناخته است.' using errcode = '22023';
  end if;

  for v_question in select value from jsonb_array_elements(v_schema)
  loop
    v_id := v_question->>'id';
    v_value := p_response->v_id;

    if not public.question_is_visible(p_response, v_question) then
      continue;
    end if;

    if coalesce((v_question->>'required')::boolean, false) then
      if public.is_blank_jsonb_answer(v_value) then
        if jsonb_typeof(v_value) = 'array' then
          raise exception 'حداقل یک گزینه برای سؤال «%» انتخاب کنید.', v_question->>'label' using errcode = '22023';
        end if;
        raise exception 'پاسخ سؤال «%» الزامی است.', v_question->>'label' using errcode = '22023';
      end if;
    end if;

    if public.is_blank_jsonb_answer(v_value) then
      continue;
    end if;

    v_validation := coalesce(v_question->'validation', '{}'::jsonb);
    v_text := coalesce(v_value #>> '{}', '');
    v_text_ascii := translate(v_text, '۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩', '01234567890123456789');

    if v_question->>'type' = 'number' then
      if jsonb_typeof(v_value) <> 'string' or v_text_ascii !~ '^[-+]?[0-9]+([.][0-9]+)?$' then
        raise exception 'مقدار سؤال «%» باید عدد باشد.', v_question->>'label' using errcode = '22023';
      end if;
      v_num := v_text_ascii::numeric;
      if v_validation ? 'min' then
        v_min := (v_validation->>'min')::numeric;
        if v_num < v_min then raise exception 'مقدار «%» کمتر از حد مجاز است.', v_question->>'label' using errcode = '22023'; end if;
      end if;
      if v_validation ? 'max' then
        v_max := (v_validation->>'max')::numeric;
        if v_num > v_max then raise exception 'مقدار «%» بیشتر از حد مجاز است.', v_question->>'label' using errcode = '22023'; end if;
      end if;
      if coalesce((v_validation->>'integer')::boolean, false) and v_num <> trunc(v_num) then
        raise exception 'مقدار «%» باید عدد صحیح باشد.', v_question->>'label' using errcode = '22023';
      end if;
    end if;

    if v_question->>'type' in ('text','textarea','select','radio','date','jalali','serial') then
      if v_validation ? 'minLength' and length(v_text) < (v_validation->>'minLength')::integer then
        raise exception 'طول «%» کمتر از حد مجاز است.', v_question->>'label' using errcode = '22023';
      end if;
      if v_validation ? 'maxLength' and length(v_text) > (v_validation->>'maxLength')::integer then
        raise exception 'طول «%» بیشتر از حد مجاز است.', v_question->>'label' using errcode = '22023';
      end if;
      if v_validation ? 'pattern' and v_text_ascii !~ (v_validation->>'pattern') then
        raise exception 'قالب سؤال «%» صحیح نیست.', v_question->>'label' using errcode = '22023';
      end if;
    end if;

    if v_question->>'type' in ('select','radio') then
      v_options := coalesce(v_question->'options','[]'::jsonb);
      if not exists (
        select 1 from jsonb_array_elements_text(v_options) opt where opt = v_text
      ) then
        raise exception 'گزینه سؤال «%» معتبر نیست.', v_question->>'label' using errcode = '22023';
      end if;
    end if;

    if v_question->>'type' = 'checkbox' then
      v_options := coalesce(v_question->'options','[]'::jsonb);
      if jsonb_typeof(v_value) <> 'array' then
        raise exception 'ساختار پاسخ سؤال «%» معتبر نیست.', v_question->>'label' using errcode = '22023';
      end if;
      if exists (
        select 1
        from jsonb_array_elements_text(v_value) selected
        where not exists (select 1 from jsonb_array_elements_text(v_options) opt where opt = selected)
      ) then
        raise exception 'یکی از گزینه‌های سؤال «%» معتبر نیست.', v_question->>'label' using errcode = '22023';
      end if;
    end if;

    if v_question->>'type' = 'date' and v_text_ascii !~ '^\d{4}-\d{2}-\d{2}$' then
      raise exception 'تاریخ میلادی «%» معتبر نیست.', v_question->>'label' using errcode = '22023';
    end if;

    if v_question->>'type' = 'jalali' and v_text_ascii !~ '^\d{4}/\d{1,2}/\d{1,2}$' then
      raise exception 'تاریخ شمسی «%» معتبر نیست.', v_question->>'label' using errcode = '22023';
    end if;

    if v_question->>'type' = 'serial' and v_text_ascii !~ '^[ابپتثجچحخدذرزژسشصضطظعغفقکگلمنوهی][0-9]{2}/[0-9]{6}$' then
      raise exception 'سریال شناسنامه «%» معتبر نیست.', v_question->>'label' using errcode = '22023';
    end if;

    v_clean_response := v_clean_response || jsonb_build_object(v_id, v_value);
  end loop;

  insert into public.responses(form_id, form_version_id, response, schema_snapshot, device_name)
  values(p_form_id, p_form_version_id, v_clean_response, v_schema, left(coalesce(p_device_name,''),120))
  returning id into v_response_id;

  return v_response_id;
end;
$$;

-- ------------------------------------------------------------
-- Publish draft atomically.
-- ------------------------------------------------------------
create or replace function public.publish_form(p_form_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_form public.forms%rowtype;
  v_next_version integer;
  v_version_id uuid;
begin
  if not public.is_admin() then
    raise exception 'دسترسی مدیر لازم است.' using errcode = '42501';
  end if;

  select * into v_form from public.forms where id = p_form_id for update;
  if not found then raise exception 'فرم پیدا نشد.' using errcode = 'P0002'; end if;

  select coalesce(max(version_number),0)+1 into v_next_version
  from public.form_versions
  where form_id = p_form_id;

  update public.form_versions
  set is_published = false
  where form_id = p_form_id and is_published = true;

  insert into public.form_versions(
    form_id, slug, version_number, title, description, auto_next,
    device_name, slogan, questions, is_published, published_at, published_by
  ) values (
    v_form.id, v_form.slug, v_next_version, v_form.title, v_form.description,
    v_form.auto_next, v_form.device_name, v_form.slogan, v_form.draft_questions,
    true, now(), auth.uid()
  ) returning id into v_version_id;

  return jsonb_build_object(
    'version_id', v_version_id,
    'version_number', v_next_version,
    'published_at', now()
  );
end;
$$;

-- ------------------------------------------------------------
-- Admin helper: delete all responses for one form.
-- ------------------------------------------------------------
create or replace function public.delete_all_form_responses(p_form_id uuid)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  if not public.is_admin() then
    raise exception 'دسترسی مدیر لازم است.' using errcode = '42501';
  end if;
  delete from public.responses where form_id = p_form_id;
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

