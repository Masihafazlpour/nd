returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.is_blank_jsonb_answer(p_value jsonb)
returns boolean
language plpgsql
immutable
as $$
begin
  if p_value is null or p_value = 'null'::jsonb then
    return true;
  end if;

  if jsonb_typeof(p_value) = 'string' and btrim(p_value #>> '{}') = '' then
    return true;
  end if;

  if jsonb_typeof(p_value) = 'array' and jsonb_array_length(p_value) = 0 then
    return true;
  end if;

  return false;
end;
$$;

