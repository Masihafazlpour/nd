create extension if not exists pgcrypto;

-- ------------------------------------------------------------
-- Profiles / roles
-- ------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null default 'admin' check (role in ('admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ------------------------------------------------------------
-- Main form (one central form by slug)
-- Draft is stored here. Published versions are immutable snapshots.
-- ------------------------------------------------------------
create table if not exists public.forms (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  title text not null,
  description text not null default '',
  auto_next boolean not null default true,
  device_name text not null default '',
  slogan text not null default '',
  draft_questions jsonb not null default '[]'::jsonb,
  draft_revision integer not null default 1 check (draft_revision > 0),
  draft_updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ------------------------------------------------------------
-- Immutable published snapshots
-- ------------------------------------------------------------
create table if not exists public.form_versions (
  id uuid primary key default gen_random_uuid(),
  form_id uuid not null references public.forms(id) on delete cascade,
  slug text not null,
  version_number integer not null check (version_number > 0),
  title text not null,
  description text not null default '',
  auto_next boolean not null default true,
  device_name text not null default '',
  slogan text not null default '',
  questions jsonb not null default '[]'::jsonb,
  is_published boolean not null default false,
  published_at timestamptz,
  published_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique(form_id, version_number)
);

create unique index if not exists uq_one_published_version_per_form
  on public.form_versions(form_id)
  where is_published = true;

create index if not exists idx_form_versions_public_slug
  on public.form_versions(slug, is_published);

-- ------------------------------------------------------------
-- Responses
-- search_text is derived from JSON for fast admin search.
-- ------------------------------------------------------------
create table if not exists public.responses (
  id uuid primary key default gen_random_uuid(),
  form_id uuid not null references public.forms(id) on delete cascade,
  form_version_id uuid not null references public.form_versions(id) on delete restrict,
  response jsonb not null default '{}'::jsonb,
  schema_snapshot jsonb not null default '[]'::jsonb,
  device_name text not null default '',
  search_text text generated always as (lower(response::text || ' ' || device_name)) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

create index if not exists idx_responses_form_created
  on public.responses(form_id, created_at desc);

create index if not exists idx_responses_search_text
  on public.responses using gin (to_tsvector('simple', search_text));

-- ------------------------------------------------------------
-- Audit logs
-- ------------------------------------------------------------
create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  admin_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text,
  entity_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_audit_logs_created
  on public.audit_logs(created_at desc);

